-- Vihan Multi Speciality Hospital - Phase 1 schema (DESIGN.md §9.3), PostgreSQL.
-- Conventions (§9.1): identity PKs, BOOLEAN flags, audit columns on every table,
-- all times IST, soft delete via is_active for master data.

-- ===== Master data =====
CREATE TABLE branch (
  branch_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code             VARCHAR(10)  NOT NULL CONSTRAINT uq_branch_code UNIQUE,  -- MLG/HZN/KDD
  name             VARCHAR(120) NOT NULL,
  address          VARCHAR(400) NOT NULL,
  city             VARCHAR(60)  NOT NULL,
  district         VARCHAR(60),
  pincode          VARCHAR(6),
  phone            VARCHAR(15),
  emergency_phone  VARCHAR(15),
  email            VARCHAR(120),
  map_url          VARCHAR(500),
  image_url        VARCHAR(500),
  opening_hours    VARCHAR(200),
  is_active        BOOLEAN DEFAULT TRUE NOT NULL,
  created_at       TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
  created_by       BIGINT,
  updated_at       TIMESTAMP,
  updated_by       BIGINT
);

CREATE TABLE speciality (
  speciality_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name             VARCHAR(80) NOT NULL CONSTRAINT uq_speciality_name UNIQUE,
  description      VARCHAR(1000),
  icon_url         VARCHAR(500),
  is_active        BOOLEAN DEFAULT TRUE NOT NULL,
  created_at       TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
  created_by       BIGINT,
  updated_at       TIMESTAMP,
  updated_by       BIGINT
);

CREATE TABLE doctor (
  doctor_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name           VARCHAR(120) NOT NULL,
  gender              VARCHAR(1)   CHECK (gender IN ('M','F','O')),
  speciality_id       BIGINT       NOT NULL REFERENCES speciality,
  qualification       VARCHAR(300) NOT NULL,           -- e.g. "MBBS, MS (Ortho)"
  designation         VARCHAR(120),                    -- e.g. "Senior Consultant"
  registration_no     VARCHAR(40)  CONSTRAINT uq_doctor_regno UNIQUE, -- TSMC reg no.
  practice_start_year INTEGER      NOT NULL,           -- experience = current year - this
  languages           VARCHAR(200),
  bio                 VARCHAR(2000),
  photo_url           VARCHAR(500),
  consultation_fee    NUMERIC(8,2),
  is_active           BOOLEAN DEFAULT TRUE NOT NULL,
  created_at          TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
  created_by          BIGINT,
  updated_at          TIMESTAMP,
  updated_by          BIGINT
);
CREATE INDEX ix_doctor_speciality ON doctor (speciality_id);

CREATE TABLE doctor_branch (
  doctor_id   BIGINT NOT NULL REFERENCES doctor,
  branch_id   BIGINT NOT NULL REFERENCES branch,
  created_at  TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
  created_by  BIGINT,
  updated_at  TIMESTAMP,
  updated_by  BIGINT,
  CONSTRAINT pk_doctor_branch PRIMARY KEY (doctor_id, branch_id)
);
CREATE INDEX ix_doctor_branch_branch ON doctor_branch (branch_id);

CREATE TABLE gallery_image (
  image_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  branch_id   BIGINT REFERENCES branch,                -- null = network-wide
  title       VARCHAR(120),
  caption     VARCHAR(500),
  image_url   VARCHAR(500) NOT NULL,
  thumb_url   VARCHAR(500) NOT NULL,
  sort_order  INTEGER DEFAULT 0 NOT NULL,
  is_active   BOOLEAN DEFAULT TRUE NOT NULL,
  created_at  TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
  created_by  BIGINT,
  updated_at  TIMESTAMP,
  updated_by  BIGINT
);

-- ===== Scheduling =====
CREATE TABLE doctor_schedule (                          -- weekly template
  schedule_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  doctor_id       BIGINT  NOT NULL REFERENCES doctor,
  branch_id       BIGINT  NOT NULL REFERENCES branch,
  day_of_week     INTEGER NOT NULL CHECK (day_of_week BETWEEN 1 AND 7), -- 1=Mon (ISO)
  start_time      VARCHAR(5) NOT NULL,                  -- 'HH24:MI'
  end_time        VARCHAR(5) NOT NULL,
  slot_minutes    INTEGER DEFAULT 20 NOT NULL CHECK (slot_minutes BETWEEN 5 AND 120),
  effective_from  DATE NOT NULL,
  effective_to    DATE,
  is_active       BOOLEAN DEFAULT TRUE NOT NULL,
  created_at      TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
  created_by      BIGINT,
  updated_at      TIMESTAMP,
  updated_by      BIGINT,
  CHECK (end_time > start_time)
);
CREATE INDEX ix_schedule_doctor ON doctor_schedule (doctor_id, day_of_week);

CREATE TABLE slot (
  slot_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  doctor_id   BIGINT    NOT NULL REFERENCES doctor,
  branch_id   BIGINT    NOT NULL REFERENCES branch,
  slot_date   DATE      NOT NULL,
  start_at    TIMESTAMP NOT NULL,
  end_at      TIMESTAMP NOT NULL,
  token_no    INTEGER   NOT NULL,                       -- position in doctor's day at branch
  status      VARCHAR(10) DEFAULT 'OPEN' NOT NULL CHECK (status IN ('OPEN','BOOKED','BLOCKED')),
  source      VARCHAR(10) DEFAULT 'TEMPLATE' NOT NULL CHECK (source IN ('TEMPLATE','MANUAL')),
  version     BIGINT DEFAULT 0 NOT NULL,                -- optimistic locking
  created_at  TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
  created_by  BIGINT,
  updated_at  TIMESTAMP,
  updated_by  BIGINT,
  CONSTRAINT uq_slot_doctor_time UNIQUE (doctor_id, start_at)  -- one place at a time
);
CREATE INDEX ix_slot_lookup ON slot (doctor_id, branch_id, slot_date, status);

CREATE TABLE doctor_leave (
  leave_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  doctor_id   BIGINT NOT NULL REFERENCES doctor,
  from_date   DATE NOT NULL,
  to_date     DATE NOT NULL,
  reason      VARCHAR(300),
  created_at  TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
  created_by  BIGINT,
  updated_at  TIMESTAMP,
  updated_by  BIGINT,
  CHECK (to_date >= from_date)
);
CREATE INDEX ix_leave_doctor ON doctor_leave (doctor_id, from_date);

CREATE TABLE branch_holiday (
  holiday_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  branch_id     BIGINT REFERENCES branch,               -- null = all branches
  holiday_date  DATE NOT NULL,
  name          VARCHAR(120) NOT NULL,
  created_at    TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
  created_by    BIGINT,
  updated_at    TIMESTAMP,
  updated_by    BIGINT
);
CREATE INDEX ix_holiday_date ON branch_holiday (holiday_date);

-- ===== Patients =====
CREATE SEQUENCE seq_uhid START WITH 1;

CREATE TABLE patient (
  patient_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uhid                 VARCHAR(20)  NOT NULL CONSTRAINT uq_patient_uhid UNIQUE, -- VMH-26-000123
  full_name            VARCHAR(120) NOT NULL,
  date_of_birth        DATE         NOT NULL,
  dob_is_estimated     BOOLEAN DEFAULT FALSE NOT NULL,  -- when only age given
  gender               VARCHAR(1)   NOT NULL CHECK (gender IN ('M','F','O')),
  mobile               VARCHAR(10)  NOT NULL,           -- not unique: families share phones
  alt_mobile           VARCHAR(10),
  aadhaar_enc          VARCHAR(200),                    -- AES-256-GCM ciphertext (Base64)
  aadhaar_hash         VARCHAR(64)  CONSTRAINT uq_patient_aadhaar UNIQUE, -- HMAC-SHA256 for exact search
  aadhaar_last4        VARCHAR(4),                      -- for masked display XXXX-XXXX-1234
  address              VARCHAR(400),
  city                 VARCHAR(60),
  blood_group          VARCHAR(5),
  emergency_name       VARCHAR(120),
  emergency_phone      VARCHAR(10),
  registered_branch_id BIGINT NOT NULL REFERENCES branch,
  consent_at           TIMESTAMP    NOT NULL,           -- privacy consent captured at registration
  is_active            BOOLEAN DEFAULT TRUE NOT NULL,
  created_at           TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
  created_by           BIGINT,
  updated_at           TIMESTAMP,
  updated_by           BIGINT
);
CREATE INDEX ix_patient_mobile ON patient (mobile);
CREATE INDEX ix_patient_name   ON patient (UPPER(full_name));

CREATE TABLE patient_medical_profile (                  -- DOCTOR-only
  patient_id           BIGINT PRIMARY KEY REFERENCES patient,
  allergies            VARCHAR(1000),
  chronic_conditions   VARCHAR(1000),
  past_surgeries       VARCHAR(1000),
  current_medications  VARCHAR(1000),
  family_history       VARCHAR(1000),
  created_at           TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
  created_by           BIGINT,
  updated_at           TIMESTAMP,
  updated_by           BIGINT
);

-- ===== Appointments & visits =====
CREATE TABLE appointment (
  appointment_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_ref      VARCHAR(20)  NOT NULL CONSTRAINT uq_appt_ref UNIQUE, -- VMH-261006-7K3Q
  slot_id          BIGINT       REFERENCES slot,        -- null for walk-in
  doctor_id        BIGINT       NOT NULL REFERENCES doctor,
  branch_id        BIGINT       NOT NULL REFERENCES branch,
  appt_date        DATE         NOT NULL,               -- denormalised for fast dashboards
  start_at         TIMESTAMP,
  token_no         INTEGER,
  patient_id       BIGINT       REFERENCES patient,     -- linked at check-in
  patient_name     VARCHAR(120) NOT NULL,               -- as entered by booker
  patient_mobile   VARCHAR(10)  NOT NULL,
  patient_age      INTEGER,
  patient_gender   VARCHAR(1)   CHECK (patient_gender IN ('M','F','O')),
  reason           VARCHAR(500),
  channel          VARCHAR(10)  NOT NULL CHECK (channel IN ('ONLINE','COUNTER','PHONE','WALK_IN')),
  status           VARCHAR(12)  DEFAULT 'BOOKED' NOT NULL
                   CHECK (status IN ('BOOKED','CHECKED_IN','COMPLETED','CANCELLED','NO_SHOW')),
  cancel_reason    VARCHAR(300),
  cancelled_by     VARCHAR(10)  CHECK (cancelled_by IN ('PATIENT','STAFF')),
  reschedule_count INTEGER DEFAULT 0 NOT NULL,          -- public limit = 2
  needs_action     BOOLEAN DEFAULT FALSE NOT NULL,      -- leave conflict
  booked_ip        VARCHAR(45),
  consent_at       TIMESTAMP    NOT NULL,               -- privacy consent on booking form
  checked_in_at    TIMESTAMP,
  completed_at     TIMESTAMP,
  version          BIGINT DEFAULT 0 NOT NULL,
  created_at       TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
  created_by       BIGINT,
  updated_at       TIMESTAMP,
  updated_by       BIGINT
);
-- A slot can have at most one non-cancelled appointment (partial unique index)
CREATE UNIQUE INDEX ux_appt_active_slot ON appointment (slot_id) WHERE status <> 'CANCELLED';
CREATE INDEX ix_appt_dashboard ON appointment (appt_date, branch_id, doctor_id, status);
CREATE INDEX ix_appt_mobile    ON appointment (patient_mobile, appt_date);
CREATE INDEX ix_appt_patient   ON appointment (patient_id);

CREATE TABLE visit (
  visit_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  appointment_id   BIGINT CONSTRAINT uq_visit_appt UNIQUE REFERENCES appointment,
  patient_id       BIGINT NOT NULL REFERENCES patient,
  doctor_id        BIGINT NOT NULL REFERENCES doctor,
  branch_id        BIGINT NOT NULL REFERENCES branch,
  visit_date       DATE   NOT NULL,
  visit_type       VARCHAR(12) DEFAULT 'OP' NOT NULL CHECK (visit_type IN ('OP','FOLLOW_UP','EMERGENCY')),
  status           VARCHAR(12) DEFAULT 'OPEN' NOT NULL CHECK (status IN ('OPEN','COMPLETED')),
  -- clinical fields (DOCTOR-only in API)
  bp_systolic      INTEGER,
  bp_diastolic     INTEGER,
  pulse            INTEGER,
  temperature_f    NUMERIC(4,1),
  spo2             INTEGER,
  weight_kg        NUMERIC(5,2),
  height_cm        NUMERIC(5,1),
  chief_complaint  VARCHAR(1000),
  diagnosis        VARCHAR(1000),
  clinical_notes   TEXT,
  advice           VARCHAR(2000),
  follow_up_date   DATE,
  created_at       TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
  created_by       BIGINT,
  updated_at       TIMESTAMP,
  updated_by       BIGINT
);
CREATE INDEX ix_visit_patient ON visit (patient_id, visit_date);
CREATE INDEX ix_visit_doctor  ON visit (doctor_id, visit_date);

CREATE TABLE prescription_item (
  item_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  visit_id       BIGINT NOT NULL REFERENCES visit,
  medicine_name  VARCHAR(200) NOT NULL,
  dosage         VARCHAR(60),                           -- 500 mg
  frequency      VARCHAR(60),                           -- 1-0-1
  duration       VARCHAR(60),                           -- 5 days
  instructions   VARCHAR(300),                          -- after food
  sort_order     INTEGER DEFAULT 0 NOT NULL,
  created_at     TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
  created_by     BIGINT,
  updated_at     TIMESTAMP,
  updated_by     BIGINT
);
CREATE INDEX ix_rx_visit ON prescription_item (visit_id);

-- ===== Security & audit =====
CREATE TABLE app_user (
  user_id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username              VARCHAR(60)  NOT NULL CONSTRAINT uq_user_username UNIQUE,
  password_hash         VARCHAR(100) NOT NULL,          -- BCrypt
  full_name             VARCHAR(120) NOT NULL,
  role                  VARCHAR(15)  NOT NULL CHECK (role IN ('DOCTOR','RECEPTIONIST','IT_ADMIN')),
  doctor_id             BIGINT CONSTRAINT uq_user_doctor UNIQUE REFERENCES doctor,
  home_branch_id        BIGINT REFERENCES branch,
  mobile                VARCHAR(10),
  email                 VARCHAR(120),
  is_active             BOOLEAN DEFAULT TRUE NOT NULL,
  must_change_password  BOOLEAN DEFAULT TRUE NOT NULL,
  failed_attempts       INTEGER DEFAULT 0 NOT NULL,
  locked_until          TIMESTAMP,
  last_login_at         TIMESTAMP,
  created_at            TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
  created_by            BIGINT,
  updated_at            TIMESTAMP,
  updated_by            BIGINT,
  CHECK ((role = 'DOCTOR' AND doctor_id IS NOT NULL) OR (role <> 'DOCTOR' AND doctor_id IS NULL))
);

CREATE TABLE refresh_token (
  token_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      BIGINT NOT NULL REFERENCES app_user,
  token_hash   VARCHAR(64) NOT NULL CONSTRAINT uq_refresh_hash UNIQUE, -- SHA-256 of token
  expires_at   TIMESTAMP NOT NULL,
  revoked      BOOLEAN DEFAULT FALSE NOT NULL,
  created_at   TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
  created_by   BIGINT,
  updated_at   TIMESTAMP,
  updated_by   BIGINT
);
CREATE INDEX ix_refresh_user ON refresh_token (user_id);

CREATE TABLE audit_log (
  audit_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      BIGINT REFERENCES app_user,              -- null = public action
  action       VARCHAR(40) NOT NULL,                    -- LOGIN, VIEW_PATIENT, VIEW_HISTORY, UPDATE_PATIENT...
  entity_type  VARCHAR(40),
  entity_id    VARCHAR(40),
  details      VARCHAR(1000),                           -- never contains Aadhaar / clinical text
  ip_address   VARCHAR(45),
  created_at   TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL
);
CREATE INDEX ix_audit_time ON audit_log (created_at);
CREATE INDEX ix_audit_user ON audit_log (user_id, created_at);
